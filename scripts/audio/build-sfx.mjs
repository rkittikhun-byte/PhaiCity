// npm run audio:build -- [--raw <rawDir>]
// Copies the sound effects listed in scripts/audio/sfx-manifest.json from the raw downloads
// (Kenney packs and Freesound previews, default assets/audio/_raw) into assets/audio/sfx/,
// and rewrites assets/audio/CREDITS.md from the same list. Refuses any source that is not CC0.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const MANIFEST = path.join(ROOT, 'scripts', 'audio', 'sfx-manifest.json');
const OUT_DIR = path.join(ROOT, 'assets', 'audio', 'sfx');
const CREDITS = path.join(ROOT, 'assets', 'audio', 'CREDITS.md');
const CC0 = /publicdomain\/zero\/1\.0|Creative Commons Zero/i;

const rawFlag = process.argv.indexOf('--raw');
const rawDir = path.resolve(rawFlag === -1 ? path.join(ROOT, 'assets', 'audio', '_raw') : process.argv[rawFlag + 1]);

const fail = (message) => {
  console.error(message);
  process.exit(1);
};

const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
const freesoundFile = path.join(rawDir, 'freesound', 'sources.json');
const freesound = fs.existsSync(freesoundFile) ? JSON.parse(fs.readFileSync(freesoundFile, 'utf8')) : {};
const kenneyLicenses = new Map();

function kenneySource(relative) {
  const pack = relative.split('/')[0];
  if (!kenneyLicenses.has(pack)) {
    const licenseFile = path.join(rawDir, 'kenney', pack, 'License.txt');
    const text = fs.existsSync(licenseFile) ? fs.readFileSync(licenseFile, 'utf8') : '';
    if (!CC0.test(text)) fail(`Kenney pack ${pack}: License.txt missing or not CC0`);
    // The pack title is the first non-empty line, e.g. "Interface Sounds (1.0)" or "RPG Audio"
    const title = text.split(/\r?\n/).map((line) => line.trim()).find((line) => line !== '') || pack;
    kenneyLicenses.set(pack, title.replace(/\s*\(\d[^)]*\)$/, ''));
  }
  return {
    from: path.join(rawDir, 'kenney', ...relative.split('/')),
    credit: `Kenney, ${kenneyLicenses.get(pack)}: \`${path.posix.basename(relative)}\``,
    url: 'https://kenney.nl',
  };
}

function freesoundSource(id) {
  const entry = freesound[id];
  if (!entry) fail(`Freesound ${id} is not in ${freesoundFile}; download it with scripts/audio/fetch-freesound.mjs`);
  if (!CC0.test(entry.license)) fail(`Freesound ${id} is not CC0 (${entry.license})`);
  return {
    from: path.join(rawDir, 'freesound', entry.file),
    credit: `"${entry.name}" by ${entry.author} (Freesound ${id})`,
    url: entry.url,
  };
}

fs.mkdirSync(OUT_DIR, { recursive: true });
const rows = [];
const files = new Set();
for (const item of manifest.files) {
  if (files.has(item.file)) fail(`Duplicate output file ${item.file}`);
  files.add(item.file);
  const source = item.kenney ? kenneySource(item.kenney) : freesoundSource(String(item.freesound));
  if (!fs.existsSync(source.from)) fail(`Missing source file ${source.from}`);
  fs.copyFileSync(source.from, path.join(OUT_DIR, item.file));
  rows.push(`| \`${item.file}\` | ${source.credit} | [link](${source.url}) | CC0 |`);
}

// Files left over from an older manifest would ship without a credit line
for (const stale of fs.readdirSync(OUT_DIR).filter((f) => !files.has(f))) {
  fs.unlinkSync(path.join(OUT_DIR, stale));
  console.log(`removed ${stale} (no longer in the manifest)`);
}

fs.writeFileSync(CREDITS, `# Sound credits

GENERATED by \`npm run audio:build\` from \`scripts/audio/sfx-manifest.json\`. Do not edit by hand.

Every sound effect in \`assets/audio/sfx/\` is CC0 (public domain). Credit is not required,
but we list every source with thanks.

| File | Source | Link | License |
|---|---|---|---|
${rows.join('\n')}
`);

console.log(`Copied ${rows.length} sounds to ${path.relative(ROOT, OUT_DIR)} and wrote ${path.relative(ROOT, CREDITS)}`);
